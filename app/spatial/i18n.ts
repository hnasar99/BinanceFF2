const catalogs: Record<Locale, Record<string, string>> = { en: {}, es, pt };

export function translate(locale: Locale, value: string): string {
  return catalogs[locale][value] || value;
}

export function interpolate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (
    Object.hasOwn(vars, key) ? String(vars[key]) : match
  ));
}

const LINE_PATTERNS: Array<[RegExp, (locale: Locale, match: RegExpMatchArray) => string]> = [
  [/^Mission (\S+) deployed — (.+)$/, (locale, match) => interpolate(translate(locale, "Mission {id} deployed — {title}"), { id: match[1], title: translateLine(locale, match[2]) })],
  [/^(\w+) joined the live squad$/, (locale, match) => interpolate(translate(locale, "{name} joined the live squad"), { name: match[1] })],
  [/^(\w+) stood down$/, (locale, match) => interpolate(translate(locale, "{name} stood down"), { name: match[1] })],
  [/^Command camera locked on (.+)$/, (locale, match) => interpolate(translate(locale, "Command camera locked on {node}"), { node: match[1] })],
  [/^Radar scan failed: (.+)$/, (locale, match) => interpolate(translate(locale, "Radar scan failed: {error}"), { error: match[1] })],
  [/^Radar live: (\d+) open routes · best spread \$([0-9.]+) · execute blocked$/, (locale, match) => interpolate(translate(locale, "Radar live: {n} open routes · best spread ${amount} · execute blocked"), { n: match[1], amount: match[2] })],
  [/^Simulation net \$([0-9.-]+) · (.+)$/, (locale, match) => interpolate(translate(locale, "Simulation net ${amount} · {source}"), { amount: match[1], source: match[2] })],
  [/^On-chain receipt (.+)$/, (locale, match) => interpolate(translate(locale, "On-chain receipt {hash}"), { hash: match[1] })],
  [/^Settlement receipt queued for (.+)$/, (locale, match) => interpolate(translate(locale, "Settlement receipt queued for {reward}"), { reward: match[1] })],
  [/^Risk gate KILL — (.+)$/, (locale, match) => interpolate(translate(locale, "Risk gate KILL — {reason}"), { reason: match[1] })],
  [/^(\w+) standing by\.$/, (locale, match) => interpolate(translate(locale, "{name} standing by."), { name: match[1] })],
  [/^(\w+)\. (.+) Status (\w+)\.$/, (locale, match) => interpolate(translate(locale, "{name}. {task}. Status {status}."), { name: match[1], task: translateLine(locale, match[2].replace(/\.\s*$/, "")), status: translate(locale, match[3]) })],
  [/^Radar live\. (\d+) open routes on BNB Smart Chain\. Execute remains blocked\.$/, (locale, match) => interpolate(translate(locale, "Radar live. {n} open routes on BNB Smart Chain. Execute remains blocked."), { n: match[1] })],
  [/^Simulation net ([0-9.-]+) dollars\. Observe only\.$/, (locale, match) => interpolate(translate(locale, "Simulation net {amount} dollars. Observe only."), { amount: match[1] })],
  [/^Radar scan failed\. (.+)$/, (locale, match) => interpolate(translate(locale, "Radar scan failed. {error}"), { error: match[1] })],
];

export function translateLine(locale: Locale, value: string): string {
  if (!value) return value;
  const exact = catalogs[locale][value];
  if (exact) return exact;
  for (const [pattern, render] of LINE_PATTERNS) {
    const match = value.match(pattern);
    if (match) return render(locale, match);
  }
  return value;
}
